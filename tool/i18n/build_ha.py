"""Builds lib/core/i18n/ha_strings.dart and docs/hausa_translations.csv
from tool/i18n/ha.tsv (English <TAB> Hausa).

The English column is written exactly as the text appears in the Dart
source (for example \\' for an apostrophe), so the keys match.

Run from the project root:  python tool/i18n/build_ha.py
"""
import csv
import os

rows = []
for line in open('tool/i18n/ha.tsv', encoding='utf-8'):
    line = line.rstrip('\n')
    if not line.strip() or line.startswith('#'):
        continue
    en, _, ha = line.partition('\t')
    if not ha.strip():
        continue
    rows.append((en, ha))


def dart_value(text):
    # Hausa uses straight apostrophes ('yan, jama'a): escape for a
    # single-quoted Dart string; keep \n as typed.
    out = text.replace("\\'", "'").replace("'", "\\'")
    return out.replace('$', '\\$')


with open('lib/core/i18n/ha_strings.dart', 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tool/i18n/build_ha.py from tool/i18n/ha.tsv.\n')
    f.write('// Edit the .tsv (or docs/hausa_translations.csv), not this file.\n\n')
    f.write('/// Hausa text for the app, keyed by the English text on screen.\n')
    f.write('/// Anything missing is shown in English.\n')
    f.write('const haStrings = <String, String>{\n')
    seen = set()
    for en, ha in rows:
        if en in seen:
            continue
        seen.add(en)
        f.write(f"  '{en}': '{dart_value(ha)}',\n")
    f.write('};\n')

os.makedirs('docs', exist_ok=True)
with open('docs/hausa_translations.csv', 'w', encoding='utf-8-sig', newline='') as f:
    w = csv.writer(f)
    w.writerow(['English (as in the app)', 'Hausa (please check and correct)'])
    for en, ha in rows:
        w.writerow([en.replace("\\'", "'").replace('\\n', ' / '),
                    ha.replace("\\'", "'").replace('\\n', ' / ')])
print(f'{len(rows)} translations written')
